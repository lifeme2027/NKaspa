    /// <para>
    /// 0xa6 is <see cref="OP_ZKPRECOMPILE"/> (Bitcoin OP_RIPEMD160).
    /// 0xa7 is <see cref="OP_BLAKE2BWITHKEY"/> (Bitcoin OP_SHA1).
