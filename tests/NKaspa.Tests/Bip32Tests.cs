        [Fact]
        public void Kaspa_prefixes_roundtrip_and_the_default_path_is_m_44h_111111h_0h()
        {
            using var master = ExtKey.CreateFromSeed(Encoders.Hex.DecodeData("000102030405060708090a0b0c0d0e0f"));
            var kprv = master.ToString(Network.Mainnet);
            var ktrv = master.ToString(Network.Testnet);
            Assert.StartsWith("kprv", kprv);
            Assert.StartsWith("ktrv", ktrv);
            Assert.Equal(111, kprv.Length);
            Assert.StartsWith("kpub", master.Neuter().ToString(Network.Mainnet));
            Assert.StartsWith("ktub", master.Neuter().ToString(Network.Testnet));
            Assert.StartsWith("ktub", master.Neuter().ToString(Network.Simnet));
            Assert.StartsWith("ktub", master.Neuter().ToString(Network.Devnet));
            Assert.Equal(HdKeyVersions.Kprv, Network.Mainnet.ExtPrivKeyVersion);
            Assert.Equal(HdKeyVersions.Ktub, Network.Devnet.ExtPubKeyVersion);

            using var parsed = ExtKey.Parse(kprv);
            Assert.Equal(master.PrivateKey.ToHex(), parsed.PrivateKey.ToHex());
            Assert.Equal(kprv, parsed.ToBase58());
            Assert.Equal(kprv, master.GetWif(Network.Mainnet));
            Assert.Equal(ktrv, master.GetWif(Network.Testnet));
            Assert.Equal(master.ToBase58(), master.ExportXprv());
            Assert.Equal(kprv, master.ExportXprv(Network.Mainnet));
            Assert.Equal(ktrv, master.ExportXprv(Network.Testnet));
            Assert.Equal("NKaspa.ExtKey", master.ToString());
            Assert.DoesNotContain(kprv, master.ToString(), StringComparison.Ordinal);
            Assert.DoesNotContain("kprv", master.ToString(), StringComparison.Ordinal);
            Assert.DoesNotContain("xprv", master.ToString(), StringComparison.Ordinal);

            Assert.Equal("m/44'/111111'/0'/0/1", KeyPath.KaspaReceive(1).ToString());
            Assert.Equal("m/44'/111111'/0'/1/0", KeyPath.KaspaChange(0).ToString());
            Assert.Equal(KeyPath.KaspaCoinType, 111111u);

            var mnemonic = new Mnemonic("abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about");
            using var hd = mnemonic.DeriveExtKey();
            using var receive = hd.Derive(KeyPath.KaspaReceive(0));
            var address = receive.PrivateKey.GetAddress(Network.Mainnet).ToString();
            Assert.StartsWith("kaspa:", address);
            Assert.True(KaspaAddress.IsValid(address));
            using var account = hd.Derive(KeyPath.KaspaAccount(0));
            var fromPublic = account.Neuter().Derive(new KeyPath("m/0/0"));
            Assert.Equal(address, fromPublic.GetAddress(Network.Mainnet).ToString());
        }

        private static void AssertChain(string seedHex, params string[] rows)
        {
            using var master = ExtKey.CreateFromSeed(Encoders.Hex.DecodeData(seedHex));
            for (var i = 0; i < rows.Length; i += 3)
            {
                var path = rows[i];
                var xpub = rows[i + 1];
                var xprv = rows[i + 2];
                var node = path == "m" ? master : master.Derive(new KeyPath(path));
                try
                {
                    Assert.Equal(xprv, node.ToBase58(HdKeyVersions.Xprv));
                    Assert.Equal(xpub, node.Neuter().ToBase58(HdKeyVersions.Xpub));
                    using var parsed = ExtKey.Parse(xprv);
                    Assert.Equal(xpub, parsed.Neuter().ToBase58());
                }
                finally
                {
                    if (!ReferenceEquals(node, master))
                    {
                        node.Dispose();
                    }
                }
            }
        }

        private static byte[] Bytes(string text)
        {
            return System.Text.Encoding.ASCII.GetBytes(text);
        }

        private static string Hex(byte[] data)
        {
            return Encoders.Hex.EncodeData(data);
        }
